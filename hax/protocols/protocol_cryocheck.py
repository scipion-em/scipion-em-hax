    def _createFilenameTemplates(self):
        """ Centralize how files are called """
        myDict = {
            'imgsFn': self._getExtraPath('input_particles.xmd'),
            'predictedFn': self._getExtraPath('md_final_predictions.xmd'), #chiedi
            'fnVol': self._getExtraPath('volume.mrc'),
        }
        self._updateFilenamesDict(myDict)
              
    # --------------------------- INSERT steps functions -----------------------
    def _insertAllSteps(self):
        self._createFilenameTemplates()
        self._insertFunctionStep(self.writeMetaDataStep)
        self._insertFunctionStep(self.trainingPredictStep)
        self._insertFunctionStep(self.createOutputStep)

    def writeMetaDataStep(self):
        imgsFn = self._getFileName('imgsFn')
        fnVol = self._getFileName('fnVol')

        inputParticles = self.inputParticles.get()
        Xdim = inputParticles.getXDim()
        newXdim = self.boxSize.get() if self.doDownsample.get() else Xdim #chiedi; noto che box_size per la mask è 64

        ih = ImageHandler()
        vol = self.vol.get().getFileName()
        ih.convert(self._getXmippFileName(vol), fnVol)
        curr_vol_dim = ImageHandler(self._getXmippFileName(vol)).getDimensions()[-1]
        if curr_vol_dim != Xdim:
            self.runJob("xmipp_image_resize",
                        "-i %s --fourier %d " % (fnVol, Xdim), numberOfMpi=1,
                        env=xmipp3.Plugin.getEnviron())
        ih.setSamplingRate(fnVol, inputParticles.getSamplingRate())

        writeSetOfParticles(inputParticles, imgsFn)

        # Resize images
        if newXdim != Xdim:
            params = "-i %s -o %s --save_metadata_stack %s --fourier %d" % \
                     (imgsFn,
                      self._getTmpPath('scaled_particles.stk'),
                      self._getExtraPath('scaled_particles.xmd'),
                      newXdim)
            if self.numberOfMpi.get() > 1:
                params += " --mpi_job_size %d" % int(inputParticles.getSize() / self.numberOfMpi.get())
            self.runJob("xmipp_image_resize", params, numberOfMpi=self.numberOfMpi.get(),
                        env=xmipp3.Plugin.getEnviron())
            moveFile(self._getExtraPath('scaled_particles.xmd'), imgsFn)


    def trainingPredictStep(self):
        md_file = self._getFileName('imgsFn')
        vol_file = self._getFileName('fnVol')
        output_path = self._getExtraPath()
        
        batch_size = self.batchSize.get()
        learningRate = self.learningRate.get()
        epochs = self.epochs.get()
        # latDim = self.latDim.get()
        sr = self.inputParticles.get().getSamplingRate()

        args = "--md %s --vol %s --sr %f --epochs %d --batch_size %d --learning_rate %f --output_path %s " \
               % (md_file, vol_file, sr, epochs, batch_size, learningRate, output_path)

        if self.lazyLoad:
            args += '--load_images_to_ram '
        else:
            if self.scratchFolder.get() is not None:
                args += '--ssd_scratch_folder %s ' % self.scratchFolder.get()

        if self.useGpu.get():
            gpu = str(self.getGpuList()[0])
        else:
            gpu = None

        program = hax.Plugin.getProgram("cryocheck", gpu)
        if not os.path.isdir(self._getExtraPath("cryocheck_model")):  
            self.runJob(program,
                        args + f'--mode train --reload {self._getExtraPath("cryoCheck")}'
                        if self.fineTune else args + '--mode train',
                        numberOfMpi=1)
        self.runJob(program, args + f'--mode predict --reload {self._getExtraPath("cryoCheck")}', numberOfMpi=1)


    def createOutputStep(self):
        inputSet = self.inputParticles.get()
        out_dir = self._getExtraPath()
        
        # File generato dalla fase di predict
        out_md_path = os.path.join(out_dir, "final_predictions.xmd")
        md = XmippMetaData(out_md_path)

        # Inizializza i due set di output per Scipion
        partSetAligned = self._createSetOfParticles('outputAlignedParticles')
        partSetAligned.copyInfo(inputSet)
        partSetAligned.setHasCTF(inputSet.hasCTF())
        partSetAligned.setAlignmentProj()

        partSetMisaligned = self._createSetOfParticles('outputMisalignedParticles')
        partSetMisaligned.copyInfo(inputSet)
        partSetMisaligned.setHasCTF(inputSet.hasCTF())
        partSetMisaligned.setAlignmentProj()

    
        idx = 0
        for particle in inputSet.iterItems():
            outParticle = Particle()
            outParticle.copyInfo(particle)
            
            
            score = float(md[idx, "misalignment_score"])
            score_heavy = int(md[idx, "misalignment_score_heavy"])
            
            outParticle.misalignment_score = Float(score)

           
            if score_heavy == 1:
                partSetAligned.append(outParticle)
            else:
                partSetMisaligned.append(outParticle)

            idx += 1

        
        self._defineOutputs(outputAlignedParticles=partSetAligned,
                            outputMisalignedParticles=partSetMisaligned)
                            
        self._defineTransformRelation(inputSet, partSetAligned)
        self._defineTransformRelation(inputSet, partSetMisaligned)


    # --------------------------- INFO functions -----------------------------
    def _summary(self):
        summary = []
        logFile = os.path.abspath(self._getLogsPath()) + "/run.stdout"
        with open(logFile, "r") as fi:
            for ln in fi:
                if ln.startswith("GPU memory has"):
                    summary.append(ln)
                    break
        return summary

    # ----------------------- VALIDATE functions -----------------------
    def _validate(self):
        """ Try to find errors on define params. """
        errors = []

        vol = self.vol.get()
       # mask = self.inputVolumeMask.get()

        if vol is None:
            errors.append("A volume is required. Please, select a valid and adequate volume for your dataset")

        return errors

    def _warnings(self):
        warnings = []

        return warnings

    # --------------------------- UTILS functions -----------------------

    def _getXmippFileName(self, filename):
        if getExt(filename) == ".mrc":
            filename += ":mrc"
        return filename


